var (
	Protocols    = []string{"vless", "hysteria2"}
	Transports   = []string{"xhttp", "tcp", "grpc"} // VLESS transports
	XHTTPModes   = []string{"auto", "packet-up", "stream-up", "stream-one"}
	Fingerprints = []string{"chrome", "firefox", "safari", "ios", "edge", "random"}
)

var (
	hostnameRe    = regexp.MustCompile(`^(?i)[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?(\.[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?)+$`)
	xhttpPathRe   = regexp.MustCompile(`^/[A-Za-z0-9/_.~-]{0,127}$`)
	grpcServiceRe = regexp.MustCompile(`^[A-Za-z0-9_.-]{1,64}$`)
)

// Network is the transport-layer protocol an inbound listens on. TCP and UDP
// ports are separate, so Hysteria2 can share 443 with a Reality inbound.
func Network(protocol string) string {
	if protocol == "hysteria2" {
		return "udp"
	}
	return "tcp"
}

// InboundInput is what the admin edits. Keys, certificates and obfuscation
// passwords are generated by the service and kept across updates.
type InboundInput struct {
	Remark   string
	Protocol string // vless (default) | hysteria2
	Port     int
	Address  string
	Enabled  bool

	// VLESS + Reality
	Transport       string
	Target          string // site Reality imitates: "www.microsoft.com" or "host:port"
	ServerName      string // SNI; for VLESS defaults to the target host, for Hysteria2 to the masquerade host
	Fingerprint     string
	XHTTPPath       string
	XHTTPMode       string
	GRPCServiceName string

	// Hysteria2
	Obfs       bool   // salamander: traffic looks like random UDP instead of QUIC
	Masquerade string // https URL shown to non-Hysteria visitors
	UpMbps     int
	DownMbps   int
}

type Inbounds struct {
	store     *store.Store
	now       func() time.Time
	changed   func()
	panelPort int
	portFree  func(network string, port int) error
}

func NewInbounds(st *store.Store, changed func(), panelPort int) *Inbounds {
	if changed == nil {
		changed = func() {}
	}
	return &Inbounds{store: st, now: time.Now, changed: changed, panelPort: panelPort, portFree: portFree}
}

func (s *Inbounds) List(ctx context.Context) ([]store.Inbound, error) {
	return s.store.ListInbounds(ctx)
}

func (s *Inbounds) Get(ctx context.Context, id int64) (store.Inbound, error) {
	return s.store.GetInbound(ctx, id)
}

func (s *Inbounds) Create(ctx context.Context, adminID int64, in InboundInput) (store.Inbound, error) {
	f, err := s.normalize(ctx, in, nil)
	if err != nil {
		return store.Inbound{}, err
	}
	switch f.Protocol {
	case "vless":
		priv, pub, err := NewRealityKeys()
		if err != nil {
			return store.Inbound{}, err
		}
		f.Settings.Reality.PrivateKey, f.Settings.Reality.PublicKey = priv, pub
		f.Settings.Reality.ShortIDs = []string{randomHex(8)}
	case "hysteria2":
		h := f.Settings.Hysteria
		if h.CertPEM, h.KeyPEM, h.PinSHA256, err = tlsutil.SelfSignedFor(h.SNI); err != nil {
			return store.Inbound{}, err
		}
		if in.Obfs {
			h.ObfsPassword = randomAlnum(24)
		}
	}

	ib, err := s.store.CreateInbound(ctx, f, s.now())
	if err != nil {
		return store.Inbound{}, err
	}
	writeAudit(ctx, s.store, s.now(), adminID, "inbound.create", "inbound", ib.ID, redacted(f))
	s.changed()
	return ib, nil
}

func (s *Inbounds) Update(ctx context.Context, adminID, id int64, in InboundInput) (store.Inbound, error) {
	cur, err := s.store.GetInbound(ctx, id)
	if err != nil {
		return store.Inbound{}, err
	}
	f, err := s.normalize(ctx, in, &cur)
	if err != nil {
		return store.Inbound{}, err
	}
	// Secrets stay: regenerating them would silently break every client.
	switch f.Protocol {
	case "vless":
		f.Settings.Reality.PrivateKey = cur.Settings.Reality.PrivateKey
		f.Settings.Reality.PublicKey = cur.Settings.Reality.PublicKey
		f.Settings.Reality.ShortIDs = cur.Settings.Reality.ShortIDs
	case "hysteria2":
		h, old := f.Settings.Hysteria, cur.Settings.Hysteria
		if h.SNI == old.SNI {
			h.CertPEM, h.KeyPEM, h.PinSHA256 = old.CertPEM, old.KeyPEM, old.PinSHA256
		} else if h.CertPEM, h.KeyPEM, h.PinSHA256, err = tlsutil.SelfSignedFor(h.SNI); err != nil {
			return store.Inbound{}, err
		}
		switch {
		case in.Obfs && old.ObfsPassword != "":
			h.ObfsPassword = old.ObfsPassword
		case in.Obfs:
			h.ObfsPassword = randomAlnum(24)
		}
	}

	ib, err := s.store.UpdateInbound(ctx, id, f, s.now())
	if err != nil {
		return store.Inbound{}, err
	}
	writeAudit(ctx, s.store, s.now(), adminID, "inbound.update", "inbound", id, redacted(f))
	s.changed()
	return ib, nil
}

func (s *Inbounds) Delete(ctx context.Context, adminID, id int64) error {
	if err := s.store.DeleteInbound(ctx, id); err != nil {
		return err
	}
	writeAudit(ctx, s.store, s.now(), adminID, "inbound.delete", "inbound", id, nil)
	s.changed()
	return nil
}

// normalize validates input and fills defaults. cur is the inbound being
// edited, nil on create.
func (s *Inbounds) normalize(ctx context.Context, in InboundInput, cur *store.Inbound) (store.InboundFields, error) {
	if in.Protocol == "" {
		in.Protocol = "vless"
	}
	f := store.InboundFields{
		Remark:   strings.TrimSpace(in.Remark),
		Protocol: in.Protocol,
		Port:     in.Port,
		Address:  strings.TrimSpace(in.Address),
		Enabled:  in.Enabled,
	}
	if n := utf8.RuneCountInString(f.Remark); n < 1 || n > 64 {
		return f, validate.Fail("remark", "1-64 characters")
	}
	if !slices.Contains(Protocols, f.Protocol) {
		return f, validate.Fail("protocol", "one of "+strings.Join(Protocols, ", "))
	}
	if cur != nil && cur.Protocol != f.Protocol {
		return f, validate.Fail("protocol", "protocol cannot be changed; create a new inbound instead")
	}
	if err := s.checkPort(ctx, f.Port, Network(f.Protocol), cur); err != nil {
		return f, err
	}
	if f.Address != "" && net.ParseIP(f.Address) == nil && !hostnameRe.MatchString(f.Address) {
		return f, validate.Fail("address", "an IP address or a domain name")
	}
	if f.Protocol == "hysteria2" {
		return f, normalizeHysteria(&f, in)
	}
	return f, normalizeVLESS(&f, in, cur)
}

func normalizeVLESS(f *store.InboundFields, in InboundInput, cur *store.Inbound) error {
	f.Transport, f.Security = in.Transport, "reality"
	if !slices.Contains(Transports, f.Transport) {
		return validate.Fail("transport", "one of "+strings.Join(Transports, ", "))
	}
	if cur != nil && cur.Transport != f.Transport {
		return validate.Fail("transport", "transport cannot be changed; create a new inbound instead")
	}
	targetHost, targetPort, err := splitTarget(strings.TrimSpace(in.Target))
	if err != nil {
		return err
	}
	sni := strings.ToLower(strings.TrimSpace(in.ServerName))
	if sni == "" {
		sni = targetHost
	}
	if !hostnameRe.MatchString(sni) {
		return validate.Fail("serverName", "a domain name, e.g. www.microsoft.com")
	}
	fp := in.Fingerprint
	if fp == "" {
		fp = "chrome"
	}
	if !slices.Contains(Fingerprints, fp) {
		return validate.Fail("fingerprint", "one of "+strings.Join(Fingerprints, ", "))
	}
	f.Settings.Reality = &store.RealitySettings{
		Target:      net.JoinHostPort(targetHost, strconv.Itoa(targetPort)),
		ServerNames: []string{sni},
		Fingerprint: fp,
	}

	switch f.Transport {
	case "xhttp":
		x := &store.XHTTPSettings{Path: strings.TrimSpace(in.XHTTPPath), Mode: in.XHTTPMode}
		if x.Path == "" {
			x.Path = "/" + randomAlnum(12)
		}
		if !xhttpPathRe.MatchString(x.Path) {
			return validate.Fail("xhttpPath", "starts with '/', up to 128 of A-Z a-z 0-9 / _ . ~ -")
		}
		if x.Mode == "" {
			x.Mode = "auto"
		}
		if !slices.Contains(XHTTPModes, x.Mode) {
			return validate.Fail("xhttpMode", "one of "+strings.Join(XHTTPModes, ", "))
		}
		f.Settings.XHTTP = x
	case "grpc":
		g := &store.GRPCSettings{ServiceName: strings.TrimSpace(in.GRPCServiceName)}
		if g.ServiceName == "" {
			g.ServiceName = randomAlnum(10)
		}
		if !grpcServiceRe.MatchString(g.ServiceName) {
			return validate.Fail("grpcServiceName", "1-64 of A-Z a-z 0-9 _ . -")
		}
		f.Settings.GRPC = g
	}
	return nil
}

const defaultMasquerade = "https://www.bing.com/"

func normalizeHysteria(f *store.InboundFields, in InboundInput) error {
	f.Transport, f.Security = "quic", "tls"
	masq := strings.TrimSpace(in.Masquerade)
	if masq == "" {
		masq = defaultMasquerade
	}
	u, err := url.Parse(masq)
	if err != nil || u.Scheme != "https" || !hostnameRe.MatchString(u.Hostname()) || u.User != nil {
		return validate.Fail("masquerade", "an https:// address of a real site, e.g. https://www.bing.com/")
	}
	sni := strings.ToLower(strings.TrimSpace(in.ServerName))
	if sni == "" {
		sni = strings.ToLower(u.Hostname())
	}
	if !hostnameRe.MatchString(sni) {
		return validate.Fail("serverName", "a domain name, e.g. www.bing.com")
	}
	for field, v := range map[string]int{"upMbps": in.UpMbps, "downMbps": in.DownMbps} {
		if v < 0 || v > 100000 {
			return validate.Fail(field, "0 (no limit) to 100000 Mbps")
		}
	}
	f.Settings.Hysteria = &store.HysteriaSettings{
		SNI: sni, Masquerade: u.String(), UpMbps: in.UpMbps, DownMbps: in.DownMbps,
	}
	return nil
}

func (s *Inbounds) checkPort(ctx context.Context, port int, network string, cur *store.Inbound) error {
	if port < 1 || port > 65535 {
		return validate.Fail("port", "1-65535")
	}
	if network == "tcp" && port == s.panelPort {
		return validate.Fail("port", "this port is used by the panel itself")
	}
	all, err := s.store.ListInbounds(ctx)
	if err != nil {
		return err
	}
	for _, other := range all {
		if other.Port == port && Network(other.Protocol) == network && (cur == nil || other.ID != cur.ID) {
			return validate.Fail("port", fmt.Sprintf("already used by inbound %q", other.Remark))
		}
	}
	// A port this inbound already holds is busy because its core listens on it.
	if cur == nil || cur.Port != port {
		if err := s.portFree(network, port); err != nil {
			return validate.Fail("port", "the port is busy or unavailable on this server")
		}
	}
	return nil
}

// SuggestPort proposes a port for a new inbound: 443 when it is free (the
// most natural port for both Reality and HTTP/3), then 8443, then a random
// high port.
func (s *Inbounds) SuggestPort(ctx context.Context, network string) int {
	candidates := []int{443, 8443}
	for range 30 {
		candidates = append(candidates, 10000+int(randomUint16()%50000))
	}
	for _, p := range candidates {
		if s.checkPort(ctx, p, network, nil) == nil {
			return p
		}
	}
	return 0
}

func randomUint16() uint16 {
	var b [2]byte
	rand.Read(b[:])
	return uint16(b[0])<<8 | uint16(b[1])
}

func portFree(network string, port int) error {
	addr := ":" + strconv.Itoa(port)
	if network == "udp" {
		c, err := net.ListenPacket("udp", addr)
		if err != nil {
			return err
		}
		return c.Close()
	}
	l, err := net.Listen("tcp", addr)
	if err != nil {
		return err
	}
	return l.Close()
}

func splitTarget(target string) (string, int, error) {
	if target == "" {
		return "", 0, validate.Fail("target", "required, e.g. www.microsoft.com")
	}
	host, portStr, err := net.SplitHostPort(target)
	if err != nil {
		host, portStr = target, "443"
	}
	host = strings.ToLower(host)
	port, err := strconv.Atoi(portStr)
	if err != nil || port < 1 || port > 65535 {
		return "", 0, validate.Fail("target", "invalid port")
	}
	if !hostnameRe.MatchString(host) {
		return "", 0, validate.Fail("target", "a domain name, e.g. www.microsoft.com")
	}
	return host, port, nil
}

// NewRealityKeys returns an X25519 key pair encoded like `xray x25519`.
func NewRealityKeys() (privateKey, publicKey string, err error) {
	k, err := ecdh.X25519().GenerateKey(rand.Reader)
	if err != nil {
		return "", "", err
	}
	enc := base64.RawURLEncoding
	return enc.EncodeToString(k.Bytes()), enc.EncodeToString(k.PublicKey().Bytes()), nil
}

// redacted drops private keys before the settings go to the audit log.
func redacted(f store.InboundFields) store.InboundFields {
	if f.Settings.Reality != nil {
		r := *f.Settings.Reality
		r.PrivateKey = ""
		f.Settings.Reality = &r
	}
	if f.Settings.Hysteria != nil {
		h := *f.Settings.Hysteria
		h.KeyPEM, h.CertPEM, h.ObfsPassword = "", "", ""
		f.Settings.Hysteria = &h
	}
	return f
}

func randomHex(n int) string {
	b := make([]byte, n)
	rand.Read(b)
	return hex.EncodeToString(b)
}

const alnum = "abcdefghijklmnopqrstuvwxyz0123456789"

func randomAlnum(n int) string {
	b := make([]byte, n)
	rand.Read(b)
	for i := range b {
		b[i] = alnum[int(b[i])%len(alnum)]
	}
	return string(b)
}

// writeAudit records a change; a failure must not undo or hide a change that
// already happened, so it is only logged.
func writeAudit(ctx context.Context, st *store.Store, now time.Time, adminID int64, action, targetType string, id int64, diff any) {
	err := st.AddAudit(ctx, store.AuditEntry{
		AdminID:    adminID,
		Action:     action,
		TargetType: targetType,
		TargetID:   strconv.FormatInt(id, 10),
		Diff:       diff,
	}, now)
	if err != nil {
		slog.Warn("audit log write failed", "action", action, "err", err)
	}
}
