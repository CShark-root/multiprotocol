// ProtocolSpec describes what an inbound of a protocol needs.
type ProtocolSpec struct {
	Core       string   // xray | hysteria | singbox
	Networks   []string // ports it listens on: tcp, udp or both
	Transports []string // allowed transports; the first is the default
	Security   string   // reality | tls | shadowtls | none
}

var protocols = map[string]ProtocolSpec{
	"vless":       {Core: "xray", Networks: []string{"tcp"}, Transports: []string{"xhttp", "tcp", "grpc"}, Security: "reality"},
	"trojan":      {Core: "xray", Networks: []string{"tcp"}, Transports: []string{"tcp", "xhttp", "grpc"}, Security: "reality"},
	"vmess":       {Core: "xray", Networks: []string{"tcp"}, Transports: []string{"ws", "tcp"}, Security: "none"},
	"shadowsocks": {Core: "xray", Networks: []string{"tcp", "udp"}, Transports: []string{"tcp"}, Security: "none"},
	"hysteria2":   {Core: "hysteria", Networks: []string{"udp"}, Transports: []string{"quic"}, Security: "tls"},
	"tuic":        {Core: "singbox", Networks: []string{"udp"}, Transports: []string{"quic"}, Security: "tls"},
	"anytls":      {Core: "singbox", Networks: []string{"tcp"}, Transports: []string{"tcp"}, Security: "tls"},
	"shadowtls":   {Core: "singbox", Networks: []string{"tcp"}, Transports: []string{"tcp"}, Security: "shadowtls"},
}

// ProtocolOrder is the order the UI offers protocols in.
var ProtocolOrder = []string{"vless", "trojan", "shadowsocks", "vmess", "hysteria2", "tuic", "anytls", "shadowtls"}

func Spec(protocol string) (ProtocolSpec, bool) {
	p, ok := protocols[protocol]
	return p, ok
}

// Networks lists the port families an inbound of this protocol occupies.
func Networks(protocol string) []string { return protocols[protocol].Networks }

// SS2022Method is the only Shadowsocks cipher offered: modern, multi-user,
// with replay protection.
const SS2022Method = "2022-blake3-aes-128-gcm"

var (
	XHTTPModes   = []string{"auto", "packet-up", "stream-up", "stream-one"}
	Fingerprints = []string{"chrome", "firefox", "safari", "ios", "edge", "random"}
)

var (
	hostnameRe    = regexp.MustCompile(`^(?i)[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?(\.[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?)+$`)
	httpPathRe    = regexp.MustCompile(`^/[A-Za-z0-9/_.~-]{0,127}$`)
	grpcServiceRe = regexp.MustCompile(`^[A-Za-z0-9_.-]{1,64}$`)
)

// InboundInput is what the admin edits. Keys, certificates and passwords
// are generated by the service and kept across updates.
type InboundInput struct {
	Remark    string
	Protocol  string // see ProtocolOrder; default vless
	Transport string // default: the protocol's first transport
	Port      int
	Address   string
	Enabled   bool

	// Reality (VLESS, Trojan) and ShadowTLS: the real site to imitate.
	Target          string // "www.microsoft.com" or "host:port"
	ServerName      string // SNI for Reality, Hysteria2, TUIC, AnyTLS
	Fingerprint     string
	XHTTPPath       string
	XHTTPMode       string
	GRPCServiceName string
	WSPath          string

	// Hysteria2
	Obfs       bool
	Masquerade string
	UpMbps     int
	DownMbps   int
}

type Inbounds struct {
	store     *store.Store
	now       func() time.Time
	changed   func()
	panelPort int
	portFree  func(network string, port int) error
}

func NewInbounds(st *store.Store, changed func(), panelPort int) *Inbounds {
	if changed == nil {
		changed = func() {}
	}
	return &Inbounds{store: st, now: time.Now, changed: changed, panelPort: panelPort, portFree: portFree}
}

func (s *Inbounds) List(ctx context.Context) ([]store.Inbound, error) {
	return s.store.ListInbounds(ctx)
}

func (s *Inbounds) Get(ctx context.Context, id int64) (store.Inbound, error) {
	return s.store.GetInbound(ctx, id)
}

func (s *Inbounds) Create(ctx context.Context, adminID int64, in InboundInput) (store.Inbound, error) {
	ib, err := s.create(ctx, in, false)
	if err != nil {
		return store.Inbound{}, err
	}
	writeAudit(ctx, s.store, s.now(), adminID, "inbound.create", "inbound", ib.ID, redacted(ib.Settings))
	s.changed()
	return ib, nil
}

func (s *Inbounds) create(ctx context.Context, in InboundInput, testKit bool) (store.Inbound, error) {
	f, err := s.normalize(ctx, in, nil)
	if err != nil {
		return store.Inbound{}, err
	}
	if err := fillSecrets(&f, in, nil); err != nil {
		return store.Inbound{}, err
	}
	f.TestKit = testKit
	return s.store.CreateInbound(ctx, f, s.now())
}

func (s *Inbounds) Update(ctx context.Context, adminID, id int64, in InboundInput) (store.Inbound, error) {
	cur, err := s.store.GetInbound(ctx, id)
	if err != nil {
		return store.Inbound{}, err
	}
	f, err := s.normalize(ctx, in, &cur)
	if err != nil {
		return store.Inbound{}, err
	}
	if err := fillSecrets(&f, in, &cur); err != nil {
		return store.Inbound{}, err
	}
	f.TestKit = cur.TestKit
	ib, err := s.store.UpdateInbound(ctx, id, f, s.now())
	if err != nil {
		return store.Inbound{}, err
	}
	writeAudit(ctx, s.store, s.now(), adminID, "inbound.update", "inbound", id, redacted(ib.Settings))
	s.changed()
	return ib, nil
}

func (s *Inbounds) Delete(ctx context.Context, adminID, id int64) error {
	if err := s.store.DeleteInbound(ctx, id); err != nil {
		return err
	}
	writeAudit(ctx, s.store, s.now(), adminID, "inbound.delete", "inbound", id, nil)
	s.changed()
	return nil
}

// normalize validates input and fills defaults. cur is the inbound being
// edited, nil on create.
func (s *Inbounds) normalize(ctx context.Context, in InboundInput, cur *store.Inbound) (store.InboundFields, error) {
	if in.Protocol == "" {
		in.Protocol = "vless"
	}
	f := store.InboundFields{
		Remark:    strings.TrimSpace(in.Remark),
		Protocol:  in.Protocol,
		Transport: in.Transport,
		Port:      in.Port,
		Address:   strings.TrimSpace(in.Address),
		Enabled:   in.Enabled,
	}
	if n := utf8.RuneCountInString(f.Remark); n < 1 || n > 64 {
		return f, validate.Fail("remark", "1-64 characters")
	}
	spec, ok := protocols[f.Protocol]
	if !ok {
		return f, validate.Fail("protocol", "one of "+strings.Join(ProtocolOrder, ", "))
	}
	if f.Transport == "" {
		f.Transport = spec.Transports[0]
	}
	if !slices.Contains(spec.Transports, f.Transport) {
		return f, validate.Fail("transport", "one of "+strings.Join(spec.Transports, ", "))
	}
	if cur != nil && (cur.Protocol != f.Protocol || cur.Transport != f.Transport) {
		return f, validate.Fail("protocol", "protocol and transport cannot be changed; create a new inbound instead")
	}
	f.Security = spec.Security
	for _, network := range spec.Networks {
		if err := s.checkPort(ctx, f.Port, network, cur); err != nil {
			return f, err
		}
	}
	if f.Address != "" && net.ParseIP(f.Address) == nil && !hostnameRe.MatchString(f.Address) {
		return f, validate.Fail("address", "an IP address or a domain name")
	}

	switch f.Protocol {
	case "vless", "trojan":
		return f, normalizeReality(&f, in)
	case "vmess":
		if f.Transport == "ws" {
			p, err := normalizePath(in.WSPath, "wsPath")
			if err != nil {
				return f, err
			}
			f.Settings.WS = &store.WSSettings{Path: p}
		}
	case "shadowsocks":
		f.Settings.Shadowsocks = &store.ShadowsocksSettings{Method: SS2022Method}
	case "hysteria2":
		return f, normalizeHysteria(&f, in)
	case "tuic", "anytls":
		sni, err := normalizeSNI(in.ServerName, "www.bing.com")
		if err != nil {
			return f, err
		}
		f.Settings.TLS = &store.TLSSettings{SNI: sni}
	case "shadowtls":
		if strings.TrimSpace(in.Target) == "" {
			in.Target = "www.microsoft.com"
		}
		host, port, err := splitTarget(strings.TrimSpace(in.Target))
		if err != nil {
			return f, err
		}
		f.Settings.ShadowTLS = &store.ShadowTLSSettings{Handshake: net.JoinHostPort(host, strconv.Itoa(port))}
		f.Settings.Shadowsocks = &store.ShadowsocksSettings{Method: SS2022Method}
	}
	return f, nil
}

func normalizeReality(f *store.InboundFields, in InboundInput) error {
	targetHost, targetPort, err := splitTarget(strings.TrimSpace(in.Target))
	if err != nil {
		return err
	}
	sni, err := normalizeSNI(in.ServerName, targetHost)
	if err != nil {
		return err
	}
	fp := in.Fingerprint
	if fp == "" {
		fp = "chrome"
	}
	if !slices.Contains(Fingerprints, fp) {
		return validate.Fail("fingerprint", "one of "+strings.Join(Fingerprints, ", "))
	}
	f.Settings.Reality = &store.RealitySettings{
		Target:      net.JoinHostPort(targetHost, strconv.Itoa(targetPort)),
		ServerNames: []string{sni},
		Fingerprint: fp,
	}

	switch f.Transport {
	case "xhttp":
		p, err := normalizePath(in.XHTTPPath, "xhttpPath")
		if err != nil {
			return err
		}
		mode := in.XHTTPMode
		if mode == "" {
			mode = "auto"
		}
		if !slices.Contains(XHTTPModes, mode) {
			return validate.Fail("xhttpMode", "one of "+strings.Join(XHTTPModes, ", "))
		}
		f.Settings.XHTTP = &store.XHTTPSettings{Path: p, Mode: mode}
	case "grpc":
		g := &store.GRPCSettings{ServiceName: strings.TrimSpace(in.GRPCServiceName)}
		if g.ServiceName == "" {
			g.ServiceName = randomAlnum(10)
		}
		if !grpcServiceRe.MatchString(g.ServiceName) {
			return validate.Fail("grpcServiceName", "1-64 of A-Z a-z 0-9 _ . -")
		}
		f.Settings.GRPC = g
	}
	return nil
}

const defaultMasquerade = "https://www.bing.com/"

func normalizeHysteria(f *store.InboundFields, in InboundInput) error {
	masq := strings.TrimSpace(in.Masquerade)
	if masq == "" {
		masq = defaultMasquerade
	}
	u, err := url.Parse(masq)
	if err != nil || u.Scheme != "https" || !hostnameRe.MatchString(u.Hostname()) || u.User != nil {
		return validate.Fail("masquerade", "an https:// address of a real site, e.g. https://www.bing.com/")
	}
	sni, err := normalizeSNI(in.ServerName, strings.ToLower(u.Hostname()))
	if err != nil {
		return err
	}
	for field, v := range map[string]int{"upMbps": in.UpMbps, "downMbps": in.DownMbps} {
		if v < 0 || v > 100000 {
			return validate.Fail(field, "0 (no limit) to 100000 Mbps")
		}
	}
	f.Settings.Hysteria = &store.HysteriaSettings{
		SNI: sni, Masquerade: u.String(), UpMbps: in.UpMbps, DownMbps: in.DownMbps,
	}
	return nil
}

func normalizeSNI(v, fallback string) (string, error) {
	sni := strings.ToLower(strings.TrimSpace(v))
	if sni == "" {
		sni = fallback
	}
	if !hostnameRe.MatchString(sni) {
		return "", validate.Fail("serverName", "a domain name, e.g. www.bing.com")
	}
	return sni, nil
}

func normalizePath(v, field string) (string, error) {
	p := strings.TrimSpace(v)
	if p == "" {
		p = "/" + randomAlnum(12)
	}
	if !httpPathRe.MatchString(p) {
		return "", validate.Fail(field, "starts with '/', up to 128 of A-Z a-z 0-9 / _ . ~ -")
	}
	return p, nil
}

// fillSecrets generates keys, certificates and passwords on create and
// carries them over on update: regenerating them would silently break every
// client. A certificate is reissued only when its SNI changes.
func fillSecrets(f *store.InboundFields, in InboundInput, cur *store.Inbound) error {
	var old store.InboundSettings
	if cur != nil {
		old = cur.Settings
	}
	if r := f.Settings.Reality; r != nil {
		if old.Reality != nil {
			r.PrivateKey, r.PublicKey, r.ShortIDs = old.Reality.PrivateKey, old.Reality.PublicKey, old.Reality.ShortIDs
		} else {
			priv, pub, err := NewRealityKeys()
			if err != nil {
				return err
			}
			r.PrivateKey, r.PublicKey, r.ShortIDs = priv, pub, []string{randomHex(8)}
		}
	}
	if h := f.Settings.Hysteria; h != nil {
		if old.Hysteria != nil && old.Hysteria.SNI == h.SNI {
			h.CertPEM, h.KeyPEM, h.PinSHA256 = old.Hysteria.CertPEM, old.Hysteria.KeyPEM, old.Hysteria.PinSHA256
		} else {
			var err error
			if h.CertPEM, h.KeyPEM, h.PinSHA256, err = tlsutil.SelfSignedFor(h.SNI); err != nil {
				return err
			}
		}
		switch {
		case in.Obfs && old.Hysteria != nil && old.Hysteria.ObfsPassword != "":
			h.ObfsPassword = old.Hysteria.ObfsPassword
		case in.Obfs:
			h.ObfsPassword = randomAlnum(24)
		}
	}
	if t := f.Settings.TLS; t != nil {
		if old.TLS != nil && old.TLS.SNI == t.SNI {
			t.CertPEM, t.KeyPEM, t.PinSHA256 = old.TLS.CertPEM, old.TLS.KeyPEM, old.TLS.PinSHA256
		} else {
			var err error
			if t.CertPEM, t.KeyPEM, t.PinSHA256, err = tlsutil.SelfSignedFor(t.SNI); err != nil {
				return err
			}
		}
	}
	if ss := f.Settings.Shadowsocks; ss != nil {
		if old.Shadowsocks != nil {
			ss.ServerPSK = old.Shadowsocks.ServerPSK
		} else {
			b := make([]byte, 16)
			rand.Read(b)
			ss.ServerPSK = base64.StdEncoding.EncodeToString(b)
		}
	}
	return nil
}

func (s *Inbounds) checkPort(ctx context.Context, port int, network string, cur *store.Inbound) error {
	if port < 1 || port > 65535 {
		return validate.Fail("port", "1-65535")
	}
	if network == "tcp" && port == s.panelPort {
		return validate.Fail("port", "this port is used by the panel itself")
	}
	all, err := s.store.ListInbounds(ctx)
	if err != nil {
		return err
	}
	for _, other := range all {
		if other.Port == port && slices.Contains(Networks(other.Protocol), network) && (cur == nil || other.ID != cur.ID) {
			return validate.Fail("port", fmt.Sprintf("already used by inbound %q", other.Remark))
		}
	}
	// A port this inbound already holds is busy because its core listens on it.
	if cur == nil || cur.Port != port {
		if err := s.portFree(network, port); err != nil {
			return validate.Fail("port", "the port is busy or unavailable on this server")
		}
	}
	return nil
}

// SuggestPort proposes a port free on all the given networks: 443 first
// (the most natural port for TLS, Reality and HTTP/3), then 8443, then a
// random high port.
func (s *Inbounds) SuggestPort(ctx context.Context, networks ...string) int {
	candidates := []int{443, 8443}
	for range 40 {
		candidates = append(candidates, 10000+int(randomUint16()%50000))
	}
next:
	for _, p := range candidates {
		for _, n := range networks {
			if s.checkPort(ctx, p, n, nil) != nil {
				continue next
			}
		}
		return p
	}
	return 0
}

// The test kit: one inbound of every protocol that needs no domain, plus a
// "test-kit" user with access to all of them, to compare protocols on a
// phone. TestKitUser is reused if it exists.
const TestKitUser = "test-kit"

var testKit = []struct{ Protocol, Transport, Remark string }{
	{"vless", "xhttp", "VLESS XHTTP"},
	{"vless", "tcp", "VLESS Vision"},
	{"vless", "grpc", "VLESS gRPC"},
	{"trojan", "tcp", "Trojan"},
	{"trojan", "xhttp", "Trojan XHTTP"},
	{"shadowsocks", "tcp", "Shadowsocks-2022"},
	{"vmess", "ws", "VMess WS"},
	{"hysteria2", "quic", "Hysteria2"},
	{"tuic", "quic", "TUIC"},
	{"anytls", "tcp", "AnyTLS"},
	{"shadowtls", "tcp", "ShadowTLS"},
}

var ErrTestKitExists = errors.New("the test kit already exists")

func (s *Inbounds) CreateTestKit(ctx context.Context, adminID int64) ([]store.Inbound, error) {
	all, err := s.store.ListInbounds(ctx)
	if err != nil {
		return nil, err
	}
	for _, ib := range all {
		if ib.TestKit {
			return nil, ErrTestKitExists
		}
	}
	var created []store.Inbound
	for _, k := range testKit {
		port := s.SuggestPort(ctx, Networks(k.Protocol)...)
		if port == 0 {
			return created, fmt.Errorf("no free port for %s", k.Remark)
		}
		ib, err := s.create(ctx, InboundInput{
			Remark: "Тест · " + k.Remark, Protocol: k.Protocol, Transport: k.Transport, Port: port,
			Target: "www.microsoft.com", Enabled: true,
		}, true)
		if err != nil {
			return created, fmt.Errorf("%s: %w", k.Remark, err)
		}
		created = append(created, ib)
	}
	if _, err := s.store.GetUserByName(ctx, TestKitUser); errors.Is(err, store.ErrNotFound) {
		_, err = s.store.CreateUser(ctx, store.UserFields{
			Name: TestKitUser, Note: "Тестовый набор", Enabled: true, ResetPeriod: "none",
		}, rand.Text(), NewUUID(), s.now())
		if err != nil {
			return created, err
		}
	} else if err != nil {
		return created, err
	}
	writeAudit(ctx, s.store, s.now(), adminID, "testkit.create", "inbound", 0, map[string]int{"inbounds": len(created)})
	s.changed()
	return created, nil
}

// DeleteTestKit removes the test-kit inbounds and user.
func (s *Inbounds) DeleteTestKit(ctx context.Context, adminID int64) (int, error) {
	all, err := s.store.ListInbounds(ctx)
	if err != nil {
		return 0, err
	}
	n := 0
	for _, ib := range all {
		if ib.TestKit {
			if err := s.store.DeleteInbound(ctx, ib.ID); err != nil {
				return n, err
			}
			n++
		}
	}
	if u, err := s.store.GetUserByName(ctx, TestKitUser); err == nil {
		if err := s.store.DeleteUser(ctx, u.ID); err != nil {
			return n, err
		}
	}
	writeAudit(ctx, s.store, s.now(), adminID, "testkit.delete", "inbound", 0, map[string]int{"inbounds": n})
	s.changed()
	return n, nil
}

func randomUint16() uint16 {
	var b [2]byte
	rand.Read(b[:])
	return uint16(b[0])<<8 | uint16(b[1])
}

func portFree(network string, port int) error {
	addr := ":" + strconv.Itoa(port)
	if network == "udp" {
		c, err := net.ListenPacket("udp", addr)
		if err != nil {
			return err
		}
		return c.Close()
	}
	l, err := net.Listen("tcp", addr)
	if err != nil {
		return err
	}
	return l.Close()
}

func splitTarget(target string) (string, int, error) {
	if target == "" {
		return "", 0, validate.Fail("target", "required, e.g. www.microsoft.com")
	}
	host, portStr, err := net.SplitHostPort(target)
	if err != nil {
		host, portStr = target, "443"
	}
	host = strings.ToLower(host)
	port, err := strconv.Atoi(portStr)
	if err != nil || port < 1 || port > 65535 {
		return "", 0, validate.Fail("target", "invalid port")
	}
	if !hostnameRe.MatchString(host) {
		return "", 0, validate.Fail("target", "a domain name, e.g. www.microsoft.com")
	}
	return host, port, nil
}

// NewRealityKeys returns an X25519 key pair encoded like `xray x25519`.
func NewRealityKeys() (privateKey, publicKey string, err error) {
	k, err := ecdh.X25519().GenerateKey(rand.Reader)
	if err != nil {
		return "", "", err
	}
	enc := base64.RawURLEncoding
	return enc.EncodeToString(k.Bytes()), enc.EncodeToString(k.PublicKey().Bytes()), nil
}

// redacted drops secrets before settings go to the audit log.
func redacted(s store.InboundSettings) store.InboundSettings {
	if s.Reality != nil {
		r := *s.Reality
		r.PrivateKey = ""
		s.Reality = &r
	}
	if s.Hysteria != nil {
		h := *s.Hysteria
		h.KeyPEM, h.CertPEM, h.ObfsPassword = "", "", ""
		s.Hysteria = &h
	}
	if s.TLS != nil {
		t := *s.TLS
		t.KeyPEM, t.CertPEM = "", ""
		s.TLS = &t
	}
	if s.Shadowsocks != nil {
		ss := *s.Shadowsocks
		ss.ServerPSK = ""
		s.Shadowsocks = &ss
	}
	return s
}

func randomHex(n int) string {
	b := make([]byte, n)
	rand.Read(b)
	return hex.EncodeToString(b)
}

const alnum = "abcdefghijklmnopqrstuvwxyz0123456789"

func randomAlnum(n int) string {
	b := make([]byte, n)
	rand.Read(b)
	for i := range b {
		b[i] = alnum[int(b[i])%len(alnum)]
	}
	return string(b)
}

// writeAudit records a change; a failure must not undo or hide a change that
// already happened, so it is only logged.
func writeAudit(ctx context.Context, st *store.Store, now time.Time, adminID int64, action, targetType string, id int64, diff any) {
	err := st.AddAudit(ctx, store.AuditEntry{
		AdminID:    adminID,
		Action:     action,
		TargetType: targetType,
		TargetID:   strconv.FormatInt(id, 10),
		Diff:       diff,
	}, now)
	if err != nil {
		slog.Warn("audit log write failed", "action", action, "err", err)
	}
}
